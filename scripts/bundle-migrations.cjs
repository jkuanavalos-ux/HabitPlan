// Embed SQL as TS so Metro can bundle it without a custom SQL transformer.
const fs = require('node:fs');
const path = require('node:path');
const dir = path.join(__dirname, '../src/db/migrations');
const journal = JSON.parse(fs.readFileSync(path.join(dir, 'meta/_journal.json'), 'utf8'));
const migrations = journal.entries.map(entry => ({ version: entry.idx + 1, name: entry.tag, sql: fs.readFileSync(path.join(dir, `${entry.tag}.sql`), 'utf8').replaceAll('--> statement-breakpoint', '') }));
fs.writeFileSync(path.join(dir, 'bundled.ts'), `// Generated by npm run db:generate. Do not edit.\nexport const migrations = ${JSON.stringify(migrations, null, 2)} as const;\n`);
